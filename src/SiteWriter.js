// Дополнительные два листа ТОЛЬКО в тестовой таблице:
// metrika_site_weekly — нормализованная строка за неделю;
// site_report_preview — структура A1:... как на вкладке «Статистика  - сайт».

var SITE_VIEW_MARKER = 'AUTOGENERATED_METRIKA_SITE_VIEW_V1';

function siteReadStorage_(sheet, columns) {
  if (!sheet || sheet.getLastRow() === 0) return [];
  var last = sheet.getLastRow();
  var actual = sheet.getRange(1, 1, 1, columns.length).getValues()[0];
  if (!headersMatch_(actual, columns)) {
    throw new Error('Лист ' + SITE_WEEKLY_SHEET + ' существует с другой схемой. Ничего не меняем.');
  }
  if (last === 1) return [];
  var data = sheet.getRange(2, 1, last - 1, columns.length).getValues();
  var list = [];
  for (var i = 0; i < data.length; i++) {
    var item = {};
    for (var j = 0; j < columns.length; j++) {
      var val = data[i][j];
      item[columns[j]] = (val === '' ? null : val);
    }
    item.start_date = cellToKeyString_(item.start_date, 'start_date');
    item.end_date = cellToKeyString_(item.end_date, 'end_date');
    list.push(item);
  }
  return list;
}

function siteRowKey_(row) {
  var values = [row.counter_id, row.start_date, row.end_date, row.definition_version];
  for (var i = 0; i < values.length; i++) {
    if (values[i] === '' || values[i] === null || typeof values[i] === 'undefined') {
      throw new Error('В строке недостаёт части ключа.');
    }
  }
  return values.join('|');
}

function siteWritePreflight_(storage, view, row, columns) {
  var data = siteReadStorage_(storage, columns);
  var wanted = siteRowKey_(row);
  var targetIndex = -1;
  var seen = {};
  for (var i = 0; i < data.length; i++) {
    var key = siteRowKey_(data[i]);
    if (seen[key]) throw new Error('В хранилище обнаружены дубли ключа ' + key + '.');
    seen[key] = true;
    if (data[i].definition_version !== SITE_DEFINITION_VERSION) {
      throw new Error('В хранилище другая версия определения. Смешивать версии недель нельзя.');
    }
    if (key === wanted) targetIndex = i;
  }
  if (targetIndex >= 0 && storage) {
    var f = storage.getRange(targetIndex + 2, 1, 1, columns.length).getFormulas()[0];
    if (rowHasFormula_(f)) throw new Error('В строке хранения есть пользовательская формула. Не перезаписываем.');
  }
  var viewIsNew = !view;
  if (!viewIsNew) {
    var marker = view.getRange(52, 1, 1, 1).getValues()[0][0];
    if (marker !== SITE_VIEW_MARKER) {
      throw new Error('Лист ' + SITE_VIEW_SHEET + ' уже существует и не принадлежит этому скрипту. Запись запрещена.');
    }
    var formulaWidth = Math.max(3, 1 + 2 * Math.max(1, data.length));
    var formulas = view.getRange(1, 1, 50, formulaWidth).getFormulas();
    for (var r = 0; r < formulas.length; r++) {
      for (var c = 0; c < formulas[r].length; c++) {
        if (formulas[r][c]) throw new Error('В ' + SITE_VIEW_SHEET + ' есть чужие формулы. Не перезаписываем.');
      }
    }
  }
  if (targetIndex >= 0) data[targetIndex] = row;
  else data.push(row);
  return { rows: data, targetIndex: targetIndex, action: targetIndex >= 0 ? 'update' : 'append' };
}

function writeSiteWeekAndView_(row, deps) {
  if (!row || row.publication !== 'exact' || row.sampled !== false || row.sample_share !== 1) {
    throw new Error('Недостоверный отчет нельзя публиковать.');
  }
  if (row.definition_version !== SITE_DEFINITION_VERSION || row.timezone !== 'Europe/Moscow') {
    throw new Error('Версия определения или timezone отличаются от site v1.');
  }
  var id = assertSpreadsheetIdAllowed(deps.spreadsheetId);
  var lock = deps.getLock();
  lock.waitLock(getMetrikaConfig().lockWaitMs);
  try {
    var book = deps.openById(id);
    var cols = siteColumns_();
    var storage = book.getSheetByName(SITE_WEEKLY_SHEET);
    var view = book.getSheetByName(SITE_VIEW_SHEET);
    var planned = siteWritePreflight_(storage, view, row, cols);
    var matrix = siteBuildView_(planned.rows);
    if (!storage) storage = book.insertSheet(SITE_WEEKLY_SHEET);
    if (!view) view = book.insertSheet(SITE_VIEW_SHEET);
    // Проверка завершена до первой записи; создание новых листов могло уже произойти.
    siteEnsureGrid_(storage, planned.rows.length + 1, cols.length);
    siteEnsureGrid_(view, 52, matrix[0].length);
    if (storage.getLastRow() === 0) {
      storage.getRange(1, 1, 1, cols.length).setValues([cols]);
    }
    var dataIndex = planned.targetIndex >= 0 ? planned.targetIndex + 2 : storage.getLastRow() + 1;
    var values = [];
    for (var i = 0; i < cols.length; i++) {
      var v = row[cols[i]];
      values.push(v === undefined || v === null ? '' : v);
    }
    storage.getRange(dataIndex, 1, 1, cols.length).setValues([values]);
    var storeFormats = [];
    for (i = 0; i < cols.length; i++) storeFormats.push(siteStorageFormat_(cols[i]));
    storage.getRange(dataIndex, 1, 1, cols.length).setNumberFormats([storeFormats]);
    view.getRange(1, 1, matrix.length, matrix[0].length).setValues(matrix);
    siteApplyViewFormats_(view, matrix[0].length);
    if (view.setFrozenRows) view.setFrozenRows(2);
    if (view.setFrozenColumns) view.setFrozenColumns(1);
    if (view.setColumnWidth) view.setColumnWidth(1, 400);
    if (view.hideRows) view.hideRows(51, 2);
    // Единственный flush после всех setValues, до releaseLock. Ошибка не гарантирует rollback.
    deps.flush();
    return { action: planned.action, rawRow: dataIndex, weeks: planned.rows.length, spreadsheetId: id };
  } finally {
    lock.releaseLock();
  }
}

function siteEnsureGrid_(sheet, minRows, minCols) {
  if (sheet.getMaxRows && sheet.insertRowsAfter && sheet.getMaxRows() < minRows) {
    sheet.insertRowsAfter(sheet.getMaxRows(), minRows - sheet.getMaxRows());
  }
  if (sheet.getMaxColumns && sheet.insertColumnsAfter && sheet.getMaxColumns() < minCols) {
    sheet.insertColumnsAfter(sheet.getMaxColumns(), minCols - sheet.getMaxColumns());
  }
}

function siteStorageFormat_(field) {
  if (field === 'start_date' || field === 'end_date' || field === 'timezone' ||
      field === 'definition_version' || field === 'fetched_at' || field === 'accuracy' ||
      field === 'traffic_attribution' || field === 'publication') return '@';
  if (field === 'sampled') return 'General';
  if (field === 'percent_new_visitors' || field === 'bounce_rate') return '0.0000%';
  if (field === 'page_depth' || field === 'visits_per_user' || field === 'sample_share') return '0.000000';
  if (field === 'avg_visit_duration_seconds') return '0.00';
  return '#,##0';
}

